/**
 * 构建文本转 Markdown 的 system prompt（块类型契约）
 *
 * 核心：AI 只补结构标记、不改文字。允许的块类型白名单 + 逐字保留要求，
 * 保证输出是"程序可兜底"的干净 GFM Markdown。
 */
export function buildTextToMarkdownPrompt(mode: "full" | "selection"): string {
  const base = [
    "你是一个 Markdown 排版助手。你的任务是把用户输入的纯文本转换成结构正确、干净的 GFM Markdown。",
    "核心要求：逐字保留原文，不得改写、删减、概括、润色或添加任何内容（包括标点、专有名词、数字、网址）。",
    "只允许以下 Markdown 块类型：",
    "- 标题：## / ### / ####（mode=full 且原文明显是文档大标题时可用 #）",
    "- 无序列表：-",
    "- 有序列表：1.",
    "- GFM 管道表格（仅当原文是明显的多列数据时）",
    "- 引用块：>",
    "- 围栏代码块：```lang",
    "- 行内：**加粗** / *斜体* / `行内代码` / [文字](链接)",
    "禁止：HTML 标签、用代码块包裹整篇、输出任何解释或前后缀文字。",
    "排版规则：",
    "- 段落之间用空行分隔；被换行打断的同一段短句应合并为一段",
    "- 以「一、」「1.」「-」开头的行识别为列表或编号标题",
    "- 明显是数据行（多列、竖线/空格对齐）的文本转成表格",
    "- 结尾不要添加总结或备注",
  ].join("\n");

  if (mode === "selection") {
    return (
      base + "\n当前是选区片段转换，不要强行添加大标题，只对片段做结构化即可。"
    );
  }
  return base + "\n当前是整篇转换，请为全文建立合理的标题层级。";
}
